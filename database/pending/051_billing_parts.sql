CREATE TABLE rental_billing_parts (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    version INT UNSIGNED NOT NULL,
    supersedes_version INT UNSIGNED NULL,
    source_namespace VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    source_key VARCHAR(180) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    number VARCHAR(100) NOT NULL,
    use_type VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    area DECIMAL(18,4) NULL,
    floor VARCHAR(100) NULL,
    address TEXT NULL,
    parent_object_id BIGINT NULL,
    physical_occupancy TINYINT NOT NULL DEFAULT 0,
    source_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    evidence_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    admission_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(id,version),
    UNIQUE KEY billing_part_source_version(source_namespace,source_key,version),
    FOREIGN KEY(id,supersedes_version) REFERENCES rental_billing_parts(id,version),
    FOREIGN KEY(parent_object_id) REFERENCES rental_objects(id),
    CHECK(use_type='LEGAL_ADDRESS'),
    CHECK(physical_occupancy=0),
    CHECK(version>0),
    CHECK((version=1 AND supersedes_version IS NULL) OR (version>1 AND supersedes_version=version-1))
) ENGINE=InnoDB;

CREATE TABLE contract_part_terms (
    id BIGINT PRIMARY KEY,
    contract_id BIGINT NOT NULL,
    part_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    part_version INT UNSIGNED NOT NULL,
    source_term_key VARCHAR(180) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    origin VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    start_date DATE NULL,
    end_date DATE NULL,
    amount DECIMAL(20,2) NULL,
    purpose TEXT NULL,
    effective_date DATE NULL,
    superseded_on DATE NULL,
    source_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    evidence_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    admission_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    command_key VARCHAR(100) NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    UNIQUE KEY contract_part_source_term(contract_id,source_term_key),
    FOREIGN KEY(contract_id) REFERENCES contracts(id),
    FOREIGN KEY(part_id,part_version) REFERENCES rental_billing_parts(id,version),
    CHECK(origin IN ('source-admitted','native-c-contract')),
    CHECK(revision>0),
    CHECK(start_date IS NULL OR end_date IS NULL OR end_date>=start_date)
) ENGINE=InnoDB;

