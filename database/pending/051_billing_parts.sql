CREATE TABLE invoice_part_scope (
    invoice_id BIGINT NOT NULL,
    source_scope_key VARCHAR(180) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    row_kind VARCHAR(6) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    ordinal INT UNSIGNED NOT NULL,
    part_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    part_version INT UNSIGNED NULL,
    scope_state VARCHAR(7) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    start_date DATE NULL,
    end_date DATE NULL,
    source_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    evidence_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    admission_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    invoice_version INT NOT NULL,
    command_key VARCHAR(100) NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    PRIMARY KEY(invoice_id,source_scope_key),
    UNIQUE KEY invoice_part_scope_order(invoice_id,ordinal),
    FOREIGN KEY(invoice_id) REFERENCES invoices(id),
    FOREIGN KEY(part_id,part_version) REFERENCES rental_billing_parts(id,version),
    CHECK(row_kind IN ('HEADER','PART')),
    CHECK(scope_state IN ('KNOWN','PARTIAL','UNKNOWN')),
    CHECK((row_kind='HEADER' AND source_scope_key='@header' AND ordinal=0 AND part_id IS NULL AND part_version IS NULL AND start_date IS NULL AND end_date IS NULL)
       OR (row_kind='PART' AND source_scope_key<>'@header' AND ordinal>0 AND part_id IS NOT NULL AND part_version IS NOT NULL)),
    CHECK(start_date IS NULL OR end_date IS NULL OR end_date>=start_date),
    CHECK(row_kind<>'PART' OR scope_state<>'KNOWN' OR (start_date IS NOT NULL AND end_date IS NOT NULL)),
    CHECK(invoice_version>0),
    CHECK(revision>0)
) ENGINE=InnoDB;
