CREATE TABLE rental_operating_admissions (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    project_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    implementation_version VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    scope_manifest_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_semantics_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    mapping_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    projection_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    admission_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    operating_start DATE NOT NULL,
    event_lower_date DATE NOT NULL,
    mode VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    before_rows_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    after_rows_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    protected_rows_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    before_path VARCHAR(500) NOT NULL,
    candidate_path VARCHAR(500) NOT NULL,
    invoice_count INT UNSIGNED NOT NULL,
    payment_count INT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY operating_source_batch(scope_manifest_sha256,owner_semantics_sha256,state_sha256,mapping_sha256),
    CHECK(mode='PERIOD_START_PRESERVE_LATER'),
    CHECK(operating_start='2026-10-01'),
    CHECK(event_lower_date='2026-09-25'),
    CHECK(invoice_count=133),
    CHECK(payment_count=114)
) ENGINE=InnoDB;

CREATE TABLE invoice_operating_membership (
    invoice_id BIGINT PRIMARY KEY,
    admission_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    origin VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    membership VARCHAR(9) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    event_date DATE NULL,
    source_namespace VARCHAR(150) NULL,
    source_collection VARCHAR(150) NULL,
    source_id VARCHAR(180) NULL,
    evidence_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    command_key VARCHAR(100) NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY(invoice_id) REFERENCES invoices(id),
    FOREIGN KEY(admission_id) REFERENCES rental_operating_admissions(id),
    CHECK(origin IN ('imported-output','native-c-manual','native-c-initial','native-c-monthly')),
    CHECK(membership IN ('OPERATING','CONTEXT','UNKNOWN')),
    CHECK(membership='UNKNOWN' OR event_date IS NOT NULL),
    CHECK(membership<>'OPERATING' OR event_date>='2026-09-25'),
    CHECK(membership<>'CONTEXT' OR event_date<'2026-09-25'),
    CHECK((origin='imported-output' AND source_namespace IS NOT NULL AND source_collection IS NOT NULL AND source_id IS NOT NULL)
       OR (origin<>'imported-output' AND source_namespace IS NULL AND source_collection IS NULL AND source_id IS NULL))
) ENGINE=InnoDB;

CREATE TABLE payment_operating_membership (
    payment_id BIGINT PRIMARY KEY,
    admission_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    origin VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    membership VARCHAR(9) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    event_date DATE NULL,
    posting_state VARCHAR(15) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_namespace VARCHAR(150) NULL,
    source_collection VARCHAR(150) NULL,
    source_id VARCHAR(180) NULL,
    evidence_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    command_key VARCHAR(100) NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY(payment_id) REFERENCES payments(id),
    FOREIGN KEY(admission_id) REFERENCES rental_operating_admissions(id),
    CHECK(origin IN ('imported-output','native-c-manual')),
    CHECK(membership IN ('OPERATING','CONTEXT','UNKNOWN')),
    CHECK(membership='UNKNOWN' OR event_date IS NOT NULL),
    CHECK(membership<>'OPERATING' OR event_date>='2026-09-25'),
    CHECK(membership<>'CONTEXT' OR event_date<'2026-09-25'),
    CHECK((origin='imported-output' AND posting_state='ALREADY_APPLIED') OR (origin='native-c-manual' AND posting_state='NATIVE')),
    CHECK((origin='imported-output' AND source_namespace IS NOT NULL AND source_collection IS NOT NULL AND source_id IS NOT NULL)
       OR (origin='native-c-manual' AND source_namespace IS NULL AND source_collection IS NULL AND source_id IS NULL))
) ENGINE=InnoDB;
