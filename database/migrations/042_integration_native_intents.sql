CREATE TABLE integration_native_sources (
    source_instance VARCHAR(200) NOT NULL PRIMARY KEY,
    project_id CHAR(36) NOT NULL,
    workflow_namespace VARCHAR(180) NOT NULL,
    profile_ref VARCHAR(100) NOT NULL,
    organization_key CHAR(36) NOT NULL,
    organization_inn VARCHAR(12) NOT NULL,
    profile_path VARCHAR(240) NOT NULL,
    profile_file_sha256 CHAR(64) NOT NULL,
    profile_sha256 CHAR(64) NOT NULL,
    config_receipt_sha256 CHAR(64) NOT NULL,
    freeze_sha256 CHAR(64) NOT NULL,
    source_version CHAR(40) NOT NULL,
    admission_ref VARCHAR(200) NOT NULL,
    enabled TINYINT NOT NULL DEFAULT 0,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE integration_native_bindings (
    id CHAR(36) NOT NULL PRIMARY KEY,
    source_instance VARCHAR(200) NOT NULL,
    collection VARCHAR(64) NOT NULL,
    logical_id VARCHAR(180) NOT NULL,
    purpose VARCHAR(100) NOT NULL DEFAULT '',
    native_type VARCHAR(100) NOT NULL,
    native_key CHAR(36) NOT NULL,
    native_version VARCHAR(250) NOT NULL,
    evidence_path VARCHAR(240) NOT NULL,
    evidence_sha256 CHAR(64) NOT NULL,
    evidence_hmac_path VARCHAR(240) NOT NULL,
    evidence_ref VARCHAR(200) NOT NULL,
    organization_key CHAR(36) NULL,
    counterparty_key CHAR(36) NULL,
    UNIQUE KEY native_binding_subject (source_instance,collection,logical_id,purpose),
    FOREIGN KEY (source_instance) REFERENCES integration_native_sources(source_instance)
) ENGINE=InnoDB;
CREATE TABLE integration_native_party_identities (
    id CHAR(36) NOT NULL PRIMARY KEY,
    source_instance VARCHAR(200) NOT NULL,
    logical_party_id VARCHAR(180) NOT NULL,
    entity_type VARCHAR(24) NOT NULL,
    source_name VARCHAR(500) NOT NULL,
    full_name VARCHAR(500) NOT NULL,
    inn VARCHAR(12) NOT NULL,
    kpp VARCHAR(9) NOT NULL,
    evidence_path VARCHAR(240) NOT NULL,
    evidence_sha256 CHAR(64) NOT NULL,
    evidence_hmac_path VARCHAR(240) NOT NULL,
    evidence_ref VARCHAR(200) NOT NULL,
    UNIQUE KEY native_party_subject (source_instance,logical_party_id),
    FOREIGN KEY (source_instance) REFERENCES integration_native_sources(source_instance)
) ENGINE=InnoDB;
CREATE TABLE integration_native_invoice_policies (
    source_instance VARCHAR(200) NOT NULL,
    invoice_kind VARCHAR(100) NOT NULL,
    contract_purpose VARCHAR(100) NOT NULL,
    invoice_service_logical_id VARCHAR(180) NOT NULL,
    currency_logical_id VARCHAR(180) NOT NULL,
    line_policy VARCHAR(40) NOT NULL DEFAULT 'approved_aggregate',
    admission_ref VARCHAR(200) NOT NULL,
    PRIMARY KEY (source_instance,invoice_kind),
    FOREIGN KEY (source_instance) REFERENCES integration_native_sources(source_instance)
) ENGINE=InnoDB;
CREATE TABLE integration_native_prepared (
    id CHAR(36) NOT NULL PRIMARY KEY,
    source_instance VARCHAR(200) NOT NULL,
    source_namespace VARCHAR(180) NOT NULL,
    logical_document_id VARCHAR(180) NOT NULL,
    step_id VARCHAR(180) NOT NULL,
    kind VARCHAR(24) NOT NULL,
    request_key CHAR(36) NOT NULL,
    actor_id BIGINT UNSIGNED NOT NULL,
    workflow_epoch VARCHAR(100) NOT NULL,
    workflow_revision BIGINT UNSIGNED NOT NULL,
    record_kind VARCHAR(24) NOT NULL,
    record_id BIGINT NOT NULL,
    record_version INT UNSIGNED NOT NULL,
    attempt_fence CHAR(36) NOT NULL,
    packet_path VARCHAR(240) NOT NULL,
    packet_sha256 CHAR(64) NOT NULL,
    context_path VARCHAR(240) NOT NULL,
    confirmation_ref VARCHAR(200) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY native_prepared_subject (source_namespace,logical_document_id,step_id,kind),
    FOREIGN KEY (source_instance) REFERENCES integration_native_sources(source_instance),
    FOREIGN KEY (actor_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE integration_native_subjects (
    id CHAR(36) NOT NULL PRIMARY KEY,
    project_id CHAR(36) NOT NULL,
    workflow_namespace VARCHAR(180) NOT NULL,
    source_instance VARCHAR(200) NOT NULL,
    entity VARCHAR(32) NOT NULL,
    logical_subject VARCHAR(180) NOT NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    prepared_id CHAR(36) NULL,
    mapping_id CHAR(36) NULL,
    claimed_confirmation_id VARCHAR(180) NULL,
    body_sha256 CHAR(64) NULL,
    UNIQUE KEY native_global_subject (project_id,workflow_namespace,source_instance,entity,logical_subject),
    FOREIGN KEY (prepared_id) REFERENCES integration_native_prepared(id),
    FOREIGN KEY (mapping_id) REFERENCES integration_native_bindings(id)
) ENGINE=InnoDB;
CREATE TABLE integration_native_intents (
    id CHAR(36) NOT NULL PRIMARY KEY,
    project_id CHAR(36) NOT NULL,
    source_instance VARCHAR(200) NOT NULL,
    prepared_id CHAR(36) NOT NULL,
    request_key CHAR(36) NOT NULL,
    actor_id BIGINT UNSIGNED NOT NULL,
    kind VARCHAR(24) NOT NULL,
    native_key CHAR(36) NOT NULL,
    command_sha256 CHAR(64) NOT NULL,
    profile_sha256 CHAR(64) NOT NULL,
    binding_sha256 CHAR(64) NOT NULL,
    prepared_sha256 CHAR(64) NOT NULL,
    payload_path VARCHAR(240) NOT NULL,
    body_path VARCHAR(240) NOT NULL,
    body_sha256 CHAR(64) NOT NULL,
    prepared_path VARCHAR(240) NOT NULL,
    confirmation_ref VARCHAR(200) NULL,
    confirmation_path VARCHAR(240) NULL,
    state VARCHAR(24) NOT NULL DEFAULT 'prepared',
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    fence CHAR(64) NULL,
    post_fence CHAR(64) NULL,
    lease_until DATETIME(6) NULL,
    post_started TINYINT NOT NULL DEFAULT 0,
    preflight_absent TINYINT NOT NULL DEFAULT 0,
    ack_path VARCHAR(240) NULL,
    readback_path VARCHAR(240) NULL,
    native_number VARCHAR(100) NULL,
    native_version VARCHAR(250) NULL,
    reason_code VARCHAR(100) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY native_business_once (project_id,source_instance,request_key),
    UNIQUE KEY native_reserved_ref (source_instance,native_key),
    FOREIGN KEY (prepared_id) REFERENCES integration_native_prepared(id),
    FOREIGN KEY (actor_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE integration_native_receipts (
    id CHAR(36) NOT NULL PRIMARY KEY,
    intent_id CHAR(36) NOT NULL,
    stage VARCHAR(100) NOT NULL,
    http_status SMALLINT UNSIGNED NOT NULL,
    sha256 CHAR(64) NOT NULL,
    raw_path VARCHAR(240) NOT NULL,
    hmac_path VARCHAR(240) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY native_receipt_once (intent_id,stage),
    FOREIGN KEY (intent_id) REFERENCES integration_native_intents(id)
) ENGINE=InnoDB;
CREATE TABLE integration_probe_records (
    id CHAR(36) NOT NULL PRIMARY KEY,
    run_id CHAR(36) NOT NULL,
    lane VARCHAR(100) NOT NULL,
    record_key VARCHAR(500) NOT NULL,
    provider VARCHAR(24) NOT NULL,
    raw_path VARCHAR(240) NOT NULL,
    raw_sha256 CHAR(64) NOT NULL,
    source_context_path VARCHAR(240) NOT NULL,
    UNIQUE KEY probe_record_once (run_id,lane,record_key),
    FOREIGN KEY (run_id) REFERENCES integration_runs(id)
) ENGINE=InnoDB;
CREATE TABLE integration_probe_files (
    id CHAR(36) NOT NULL PRIMARY KEY,
    run_id CHAR(36) NOT NULL,
    record_id CHAR(36) NOT NULL,
    provider VARCHAR(24) NOT NULL,
    operation VARCHAR(24) NOT NULL,
    equivalence_sha256 CHAR(64) NOT NULL,
    status VARCHAR(24) NOT NULL,
    result_code VARCHAR(100) NULL,
    sha256 CHAR(64) NULL,
    byte_size BIGINT UNSIGNED NULL,
    private_path VARCHAR(240) NULL,
    signature_path VARCHAR(240) NULL,
    receipt_path VARCHAR(240) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    finished_at DATETIME(6) NULL,
    INDEX probe_file_fence (provider,equivalence_sha256,status),
    FOREIGN KEY (record_id) REFERENCES integration_probe_records(id)
) ENGINE=InnoDB;
CREATE TABLE integration_file_fences (
    provider VARCHAR(24) NOT NULL,
    equivalence_sha256 CHAR(64) NOT NULL,
    id CHAR(36) NOT NULL UNIQUE,
    source_id VARCHAR(500) NOT NULL,
    account_id VARCHAR(100) NOT NULL,
    operation VARCHAR(24) NOT NULL,
    source_context_sha256 CHAR(64) NOT NULL,
    profile_identity_sha256 CHAR(64) NOT NULL,
    status VARCHAR(24) NOT NULL,
    owner_run_id CHAR(36) NULL,
    owner_document_id CHAR(36) NULL,
    claim_key CHAR(36) NULL,
    raw_sha256 CHAR(64) NULL,
    byte_size BIGINT UNSIGNED NULL,
    private_path VARCHAR(240) NULL,
    signature_path VARCHAR(240) NULL,
    receipt_path VARCHAR(240) NULL,
    result_code VARCHAR(100) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    finished_at DATETIME(6) NULL,
    PRIMARY KEY (provider,equivalence_sha256)
) ENGINE=InnoDB;
